ROUND_CONSTANTS = (0x9E, 0xB9, 0xD4, 0xEF, 0x0A, 0x25, 0x40, 0x5B)


def _rotl8(value: int, shift: int) -> int:
    shift %= 8
    if shift == 0:
        return value & 0xFF
    return ((value << shift) | (value >> (8 - shift))) & 0xFF


def _rotl16(value: int, shift: int) -> int:
    shift %= 16
    if shift == 0:
        return value & 0xFFFF
    return ((value << shift) | (value >> (16 - shift))) & 0xFFFF


def round_keys(key: int) -> list[int]:
    keys = []
    for index in range(8):
        rotated = _rotl16(key, 3 * index)
        high, low = (rotated >> 8) & 0xFF, rotated & 0xFF
        high_mix = SBOX[high ^ ROUND_CONSTANTS[index]]
        low_mix = _rotl8(SBOX[low ^ ((ROUND_CONSTANTS[index] << 1) & 0xFF)], (index % 7) + 1)
        keys.append(high_mix ^ low_mix)
    return keys


def encrypt_block(block: int, key: int) -> int:
    left, right = (block >> 8) & 0xFF, block & 0xFF
    for round_key in round_keys(key):
        left, right = right, left ^ _rotl8(SBOX[(right ^ round_key) & 0xFF], 1)
    return ((left << 8) | right) & 0xFFFF


def decrypt_block(block: int, key: int) -> int:
    left, right = (block >> 8) & 0xFF, block & 0xFF
    for round_key in reversed(round_keys(key)):
        left, right = right ^ _rotl8(SBOX[(left ^ round_key) & 0xFF], 1), left
    return ((left << 8) | right) & 0xFFFF
